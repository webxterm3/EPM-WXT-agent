package agent

import (
	"crypto/sha256"
	"encoding/hex"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func writeTemp(t *testing.T, content string) string {
	t.Helper()
	p := filepath.Join(t.TempDir(), "pkg.dmg")
	if err := os.WriteFile(p, []byte(content), 0o600); err != nil {
		t.Fatal(err)
	}
	return p
}

func sumOf(content string) string {
	h := sha256.Sum256([]byte(content))
	return hex.EncodeToString(h[:])
}

// Every failure here must be CLOSED.
//
// A package runs as root or SYSTEM. A failed update leaves a working agent; an
// unverified one may leave something else entirely — so "I could not check
// this" has to refuse, not shrug.
func TestAnUnverifiablePackageIsRefused(t *testing.T) {
	const body = "installer bytes"
	file := writeTemp(t, body)
	const url = "http://host:8082/agent/download/wxt-agent-arm64.dmg"

	t.Run("nothing published at all", func(t *testing.T) {
		if err := verifyPackage(file, url, map[string]string{}); err == nil {
			t.Fatal("a package was accepted with no published hashes — the download " +
				"was the whole of the trust decision, which is the bug this removes")
		}
	})

	t.Run("published, but not this package", func(t *testing.T) {
		sums := map[string]string{"wxt-agent-amd64.dmg": sumOf(body)}
		err := verifyPackage(file, url, sums)
		if err == nil {
			t.Fatal("a package absent from the sums file was accepted")
		}
		if !strings.Contains(err.Error(), "not listed") {
			t.Errorf("error %q does not say the package was not published", err)
		}
	})

	t.Run("the bytes do not match", func(t *testing.T) {
		sums := map[string]string{"wxt-agent-arm64.dmg": sumOf("something else entirely")}
		err := verifyPackage(file, url, sums)
		if err == nil {
			t.Fatal("a package whose hash did not match was accepted")
		}
		if !strings.Contains(err.Error(), "does not match") {
			t.Errorf("error %q does not say the hash mismatched", err)
		}
	})

	t.Run("a matching package is accepted", func(t *testing.T) {
		sums := map[string]string{"wxt-agent-arm64.dmg": sumOf(body)}
		if err := verifyPackage(file, url, sums); err != nil {
			t.Errorf("a correct package was refused: %v", err)
		}
	})
}

// The three failures mean different things. The first two are a deployment
// out of step; the third is somebody altering what the fleet installs. An
// operator reading the log has to be able to tell them apart.
func TestTheThreeFailuresReadDifferently(t *testing.T) {
	file := writeTemp(t, "x")
	const url = "http://host/agent/download/pkg.dmg"

	none := verifyPackage(file, url, map[string]string{}).Error()
	missing := verifyPackage(file, url, map[string]string{"other.dmg": sumOf("x")}).Error()
	wrong := verifyPackage(file, url, map[string]string{"pkg.dmg": sumOf("y")}).Error()

	if none == missing || missing == wrong || none == wrong {
		t.Error("two different failures produce the same message")
	}
}

// The hashes must come from the same host as the bytes. Two sources means one
// host can supply the package and another can vouch for it.
func TestTheHashesComeFromBesideThePackage(t *testing.T) {
	got, err := sumsURLFor("http://host:8082/agent/download/wxt-agent-arm64.dmg?t=123")
	if err != nil {
		t.Fatal(err)
	}
	const want = "http://host:8082/agent/download/SHA256SUMS"
	if got != want {
		t.Errorf("got %q, want %q", got, want)
	}
}

// shasum output is "<hex>  <name>". Real files pick up comments, blank lines
// and the "*" binary marker, and one odd line must not stop the whole fleet
// updating.
func TestSumsParsingSurvivesARealFile(t *testing.T) {
	raw := `
# generated by make deploy-binaries

` + sumOf("a") + `  wxt-agent-arm64.dmg
` + sumOf("b") + ` *wxt-agent-amd64.exe
` + sumOf("c") + `  ./wxt-agent-macos-arm64.tar.gz
not-a-hash  junk.dmg
deadbeef  tooshort.dmg
`
	sums := parseSums([]byte(raw))

	for name, want := range map[string]string{
		"wxt-agent-arm64.dmg":          sumOf("a"),
		"wxt-agent-amd64.exe":          sumOf("b"),
		"wxt-agent-macos-arm64.tar.gz": sumOf("c"),
	} {
		if sums[name] != want {
			t.Errorf("%s = %q, want %q", name, sums[name], want)
		}
	}

	for _, junk := range []string{"junk.dmg", "tooshort.dmg"} {
		if _, ok := sums[junk]; ok {
			t.Errorf("%s was parsed as a valid hash", junk)
		}
	}
}

// A hash is compared case-insensitively, because tools differ, but it is
// stored lowercase so a comparison never turns on the formatting of the file.
func TestHashesAreComparedWithoutCase(t *testing.T) {
	body := "installer"
	file := writeTemp(t, body)
	upper := strings.ToUpper(sumOf(body))

	sums := parseSums([]byte(upper + "  pkg.dmg\n"))
	if err := verifyPackage(file, "http://host/agent/download/pkg.dmg", sums); err != nil {
		t.Errorf("an uppercase hash was rejected: %v", err)
	}
}
